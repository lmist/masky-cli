// Command docs regenerates the command reference and API coverage matrix.
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/lmist/masky-cli/internal/cli"
	"github.com/lmist/masky-cli/internal/spec"
	"github.com/spf13/cobra"
)

func main() {
	root := cli.NewRoot("dev")
	root.InitDefaultCompletionCmd()
	root.InitDefaultHelpCmd()
	var b strings.Builder
	b.WriteString("# Command reference\n\nGenerated by `go run ./cmd/docs`. Do not edit by hand.\n\nAll commands accept the global flags below. JSON is the default output; `--format table` is optional.\n\n```text\n")
	b.WriteString(root.PersistentFlags().FlagUsages())
	b.WriteString("```\n")
	var visit func(*cobra.Command)
	visit = func(c *cobra.Command) {
		if c != root && !c.Hidden {
			fmt.Fprintf(&b, "\n## `%s`\n\n%s\n\n```text\n%s\n```\n", c.CommandPath(), c.Short, c.UseLine())
			if c.Long != "" {
				b.WriteString("\n" + c.Long + "\n")
			}
			if c.LocalNonPersistentFlags().HasAvailableFlags() {
				b.WriteString("\n```text\n" + c.LocalNonPersistentFlags().FlagUsages() + "```\n")
			}
		}
		for _, child := range c.Commands() {
			visit(child)
		}
	}
	visit(root)
	if err := os.WriteFile("docs/COMMANDS.md", []byte(b.String()), 0644); err != nil {
		panic(err)
	}
	endpoints, err := spec.Load()
	if err != nil {
		panic(err)
	}
	sort.Slice(endpoints, func(i, j int) bool { return endpoints[i].Command < endpoints[j].Command })
	b.Reset()
	fmt.Fprintf(&b, "# API coverage\n\n%d named operations: 45 from the pinned OpenAPI document and 14 from Masky's linked API reference. Every row has an independent HTTP contract fixture.\n\nGenerated by `go run ./cmd/docs`. Sources were retrieved on 2026-10-12. See [API notes](API-NOTES.md) for reconciliation details.\n\n| Command | Method and path | Authentication | Source |\n| --- | --- | --- | --- |\n", len(endpoints))
	for _, e := range endpoints {
		fmt.Fprintf(&b, "| `masky %s` | `%s %s` | %s | %s |\n", e.Command, e.Method, e.Path, e.Auth, e.Source)
	}
	b.WriteString("\nAdditional local/workflow commands: auth profiles/login/logout/use/status, direct api, videos/speak/conversations/donations wait, oauth authorize/exchange, share url/live/resolve, version, and shell completion.\n\n`optional` sends an available token but allows anonymous calls. `none` never sends a bearer. `session` requires MASKY_SESSION_TOKEN. `nostr` requires a pre-signed authorization file.\n")
	if err := os.WriteFile("docs/API-COVERAGE.md", []byte(b.String()), 0644); err != nil {
		panic(err)
	}
}
